// Trace check. [BCC-PKG-3]
//
// Every requirement in openspec/specs/ carries an ID of the form [BCC-<CAP>-<n>]. Code and tests cite the IDs they
// implement or prove. This joins both sides, so "is this requirement built, and is it proven?" is a command,
// not an opinion.
//
// Always fails on: a duplicate requirement ID, a citation of an ID that no spec defines.
// With --strict it also fails when a requirement lacks an implementation or evidence.
//
// Usage: node tools/trace.mjs [--strict] [--write] [--check]   (--write updates docs/traceability.md, --check fails when
// it is out of date)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ID_RE = /\bBCC-[A-Z]+-\d+\b/g;
const REQ_RE = /^### Requirement: \[(BCC-[A-Z]+-\d+)\] (.+)$/;
const SKIP_DIRS = new Set(['node_modules', 'dist', 'build', 'coverage', '.git', '_intern', 'openspec', 'docs']);
const SOURCE_RE = /\.(mjs|cjs|js|jsx|ts|tsx)$/;
// The view's generated copy of core/src (tools/sync-view-core.mjs) would list every core file twice.
const SKIP_PATHS = new Set(['budget-view/src/core']);

const walk = (dir, out = [], root = dir) => {
  if (!fs.existsSync(dir)) return out;
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    if (SKIP_DIRS.has(e.name)) continue;
    const f = path.join(dir, e.name);
    if (SKIP_PATHS.has(path.relative(root, f).split(path.sep).join('/'))) continue;
    if (e.isDirectory()) walk(f, out, root);
    else out.push(f);
  }
  return out;
};

// Two kinds of evidence, kept apart: a unit test proves logic without a project; a live check
// (end-to-end, Playwright, read-only verification against the sandbox) proves behaviour in a real project.
const isTest = (rel) => /\.(test|spec)\.[cm]?[jt]sx?$/.test(rel) || /(^|\/)tests?\//.test(rel);
// A unit test inside an e2e folder stays a unit test.
const isLiveCheck = (rel) => !/\.(test|spec)\.[cm]?[jt]sx?$/.test(rel) && (/(^|\/)e2e\//.test(rel) || /\.e2e\.[cm]?[jt]sx?$/.test(rel));

export function buildMatrix(root) {
  const errors = [];
  const reqs = new Map();
  const specsDir = path.join(root, 'openspec/specs');

  for (const cap of fs.existsSync(specsDir) ? fs.readdirSync(specsDir) : []) {
    const file = path.join(specsDir, cap, 'spec.md');
    if (!fs.existsSync(file)) continue;
    for (const line of fs.readFileSync(file, 'utf8').split('\n')) {
      const m = line.match(REQ_RE);
      if (!m) continue;
      const [, id, title] = m;
      if (reqs.has(id)) {
        errors.push(`duplicate requirement ${id} in specs ${reqs.get(id).cap} and ${cap}`);
        continue;
      }
      reqs.set(id, { id, cap, title, impl: [], tests: [], live: [] });
    }
  }

  for (const f of walk(root)) {
    if (!SOURCE_RE.test(f)) continue;
    const rel = path.relative(root, f).split(path.sep).join('/');
    const bucket = isLiveCheck(rel) ? 'live' : isTest(rel) ? 'tests' : 'impl';
    for (const id of new Set(fs.readFileSync(f, 'utf8').match(ID_RE) ?? [])) {
      const r = reqs.get(id);
      if (!r) {
        errors.push(`unknown requirement ${id} cited in ${rel}`);
        continue;
      }
      if (!r[bucket].includes(rel)) r[bucket].push(rel);
    }
  }

  const rows = [...reqs.values()].sort((a, b) => a.id.localeCompare(b.id, 'en', { numeric: true }));
  return { rows, errors };
}

export function statusOf(r) {
  const proven = r.tests.length > 0 || r.live.length > 0;
  if (r.impl.length && proven) return 'traced';
  if (r.impl.length) return 'unproven';
  if (proven) return 'no implementation';
  return 'not built';
}

export function renderMarkdown(rows) {
  const files = (list) => list.map((f) => `\`${f}\``).join('<br>') || '-';
  let md = '# Traceability matrix\n\n';
  md += 'Generated by `node tools/trace.mjs --write`. Every requirement in `openspec/specs/` is joined to the files\n';
  md += 'that cite its ID. Unit tests prove logic without a project; live checks (end-to-end and Playwright) prove\n';
  md += 'behaviour in a sandbox project. A requirement with an implementation but no evidence is `unproven`.\n\n';
  md += '| ID | Capability | Requirement | Implementation | Unit test | Live check | Status |\n';
  md += '|---|---|---|---|---|---|---|\n';
  for (const r of rows) {
    md += `| \`${r.id}\` | ${r.cap} | ${r.title} | ${files(r.impl)} | ${files(r.tests)} | ${files(r.live)} | ${statusOf(r)} |\n`;
  }
  return md + `\n${summary(rows)}\n`;
}

const summary = (rows) => {
  const counts = {};
  for (const r of rows) counts[statusOf(r)] = (counts[statusOf(r)] ?? 0) + 1;
  return `**${rows.length} requirements**: ` + Object.entries(counts).map(([k, v]) => `${v} ${k}`).join(', ') + '.';
};

// True when docs/traceability.md differs from what --write would produce now.
export function staleMatrix(root) {
  const file = path.join(root, 'docs/traceability.md');
  return !fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== renderMarkdown(buildMatrix(root).rows);
}

function main(argv) {
  const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
  const { rows, errors } = buildMatrix(root);
  if (argv.includes('--write')) fs.writeFileSync(path.join(root, 'docs/traceability.md'), renderMarkdown(rows));
  if (argv.includes('--check') && staleMatrix(root)) errors.push('docs/traceability.md is out of date (run node tools/trace.mjs --write)');

  for (const r of rows) {
    const ev = [r.tests.length ? 'unit' : null, r.live.length ? 'live' : null].filter(Boolean).join('+') || '-';
    console.log(`  ${r.id.padEnd(15)} ${statusOf(r).padEnd(18)} ${ev.padEnd(10)} ${r.title.slice(0, 60)}`);
  }
  console.log(`\n${summary(rows)}`);

  for (const e of errors) console.error(`error: ${e}`);
  const gaps = rows.filter((r) => statusOf(r) !== 'traced');
  if (argv.includes('--strict') && gaps.length) console.error(`${gaps.length} requirement(s) not fully traced.`);
  return errors.length || (argv.includes('--strict') && gaps.length) ? 1 : 0;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  process.exitCode = main(process.argv.slice(2));
}
